export function makeAiNote(cfg: {
  id: string;
  moduleId: string;
  lessonId: string;
  title: string;
  intro: string;
  simple: string;
  detailed: string;
  concepts: string;
  steps: string;
  codeLang?: 'python' | 'java';
  code?: string;
  practicalNote: string;
  realWorld: string;
  important: string;
  mistakes: string;
  summary: string;
  shortQ: string;
  longQ: string;
  mcq: string;
  exercise: string;
}): SeedStudyNoteDef {
  const codeBlock =
    cfg.code && cfg.codeLang
      ? [
          '',
          `Illustrative ${cfg.codeLang.toUpperCase()} Example:`,
          '```' + cfg.codeLang,
          cfg.code,
          '```',
        ].join('\n')
      : '';
  return {
    id: cfg.id,
    moduleId: cfg.moduleId,
    lessonId: cfg.lessonId,
    title: cfg.title,
    topicIntroduction: cfg.intro,
    simpleExplanation: cfg.simple,
    detailedExplanation: cfg.detailed,
    keyConcepts: cfg.concepts,
    stepByStepExplanation: cfg.steps,
    practicalExamples: [cfg.practicalNote, codeBlock].filter(Boolean).join('\n'),
    realWorldApplications: cfg.realWorld,
    importantPoints: cfg.important,
    commonMistakes: cfg.mistakes,
    summary: cfg.summary,
    practiceQuestions: [
      '### Short-Answer Questions',
      cfg.shortQ,
      '',
      '### Long-Answer Questions',
      cfg.longQ,
      '',
      '### Multiple-Choice Questions (With Answers & Explanations)',
      cfg.mcq,
    ].join('\n'),
    domainSupplement: ['### Applied AI & Data Lab Exercise', cfg.exercise].join('\n'),
  };
}

