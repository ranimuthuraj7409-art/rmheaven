export function makeDesignNote(cfg: {
  id: string;
  moduleId: string;
  lessonId: string;
  title: string;
  intro: string;
  simple: string;
  detailed: string;
  concepts: string;
  steps: string;
  practicalExamples: string;
  realWorld: string;
  important: string;
  mistakes: string;
  summary: string;
  shortQ: string;
  longQ: string;
  mcq: string;
  designPrinciples: string;
  toolsWorkflow: string;
  assignmentTask: string;
}): SeedStudyNoteDef {
  return {
    id: cfg.id,
    moduleId: cfg.moduleId,
    lessonId: cfg.lessonId,
    title: cfg.title,
    topicIntroduction: cfg.intro,
    simpleExplanation: cfg.simple,
    detailedExplanation: cfg.detailed,
    keyConcepts: cfg.concepts,
    stepByStepExplanation: cfg.steps,
    practicalExamples: cfg.practicalExamples,
    realWorldApplications: cfg.realWorld,
    importantPoints: cfg.important,
    commonMistakes: cfg.mistakes,
    summary: cfg.summary,
    practiceQuestions: [
      '### Short-Answer Questions',
      cfg.shortQ,
      '',
      '### Long-Answer Questions',
      cfg.longQ,
      '',
      '### Multiple-Choice Questions (With Answers & Explanations)',
      cfg.mcq,
    ].join('\n'),
    domainSupplement: [
      '### Core Design Principles',
      cfg.designPrinciples,
      '',
      '### Studio Tool Workflow & Practical Exercise',
      cfg.toolsWorkflow,
      '',
      '**Design Assignment:**',
      cfg.assignmentTask,
    ].join('\n'),
  };
}

